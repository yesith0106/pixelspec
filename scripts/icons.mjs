// Rules
// - 18-unit grid, viewBox "0 0 18 18". Outline strokes of 1.5 with round caps and joins. Single color.
// - One live area: every glyph's rendered bounds fit a 14×14 box centred in the grid (2u padding),
//   so path extents stay within 2.75…15.25. Square-ish glyphs fill 13–14u, round glyphs use a
//   12.5u circle (14u rendered) so they look the same size as squares.
// - No fills except tiny accents (dots and squares ≤ 2.5u): bullets, pupils, the pixel.
// - Overlaps are drawn with gaps, not masks.
// - Logo tie-in: the small solid square is "the selected pixel" (focus, spacing, padding, guides, gaps).

export const GRID = 18;
const W = 1.5;
const n = (v) => +(+v).toFixed(2);

const stroke = (w = W) => `fill="none" stroke="currentColor" stroke-width="${w}" stroke-linecap="round" stroke-linejoin="round"`;
/** Line through points. */
const L = (pts) => `<path d="M${pts.map(([x, y]) => `${n(x)} ${n(y)}`).join('L')}" ${stroke()}/>`;
/** Outline path. */
const O = (d, extra = '') => `<path d="${d}" ${stroke()}${extra}/>`;
/** Outline rounded rect. */
const OR = (x, y, w, h, r) => `<rect x="${n(x)}" y="${n(y)}" width="${n(w)}" height="${n(h)}" rx="${n(r)}" ${stroke()}/>`;
/** Outline circle / ellipse. */
const OC = (cx, cy, r) => `<circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r)}" ${stroke()}/>`;
const OE = (cx, cy, rx, ry, extra = '') => `<ellipse cx="${n(cx)}" cy="${n(cy)}" rx="${n(rx)}" ry="${n(ry)}" ${stroke()}${extra}/>`;
/** Solid accents (≤ 2.5u). */
const D = (cx, cy, r = 0.9) => `<circle cx="${n(cx)}" cy="${n(cy)}" r="${n(r)}" fill="currentColor"/>`;
const SQ = (cx, cy, s = 2.5, r = 0.6) => `<rect x="${n(cx - s / 2)}" y="${n(cy - s / 2)}" width="${n(s)}" height="${n(s)}" rx="${n(r)}" fill="currentColor"/>`;
const F = (d) => `<path d="${d}" fill="currentColor"/>`;

/** Four-point sparkle centred on (cx, cy), radius r. */
function star(cx, cy, r, k = 0.22) {
  const a = r * k;
  return `M${n(cx)} ${n(cy - r)}Q${n(cx + a)} ${n(cy - a)} ${n(cx + r)} ${n(cy)}Q${n(cx + a)} ${n(cy + a)} ${n(cx)} ${n(cy + r)}Q${n(cx - a)} ${n(cy + a)} ${n(cx - r)} ${n(cy)}Q${n(cx - a)} ${n(cy - a)} ${n(cx)} ${n(cy - r)}Z`;
}

