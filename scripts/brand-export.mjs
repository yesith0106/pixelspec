// Brand export: `npm run brand`
// 1. Writes src/brand.gen.ts for the product (tokens, the mark and its icons). `--product` stops here; `--check` fails on drift.
// 2. Writes standalone logo SVGs to site/assets/logo/ from site/assets/brand.js.
// 3. Writes the icon sprite site/assets/icons.svg from scripts/icons.mjs (our own filled set).
// 4. Screenshots the social cards in site/brand/posters/ to PNG with headless Chrome.
//    Set CHROME=/path/to/chrome if it isn't found. Pass --svg to skip the PNGs.
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import vm from 'node:vm';
import { ICONS, PRODUCT_ICONS } from './icons.mjs';

const root = fileURLToPath(new URL('..', import.meta.url));
const at = (...p) => join(root, ...p);

/* ---------- load the logo engine in a sandbox */
const sandbox = { window: {}, document: undefined };
sandbox.window.window = sandbox.window;
vm.runInNewContext(readFileSync(at('site/assets/brand.js'), 'utf8'), sandbox);
const PS = sandbox.window.PS;

/* ---------- tokens from ps.css :root */
const css = readFileSync(at('site/assets/ps.css'), 'utf8');
const tok = {};
for (const [, k, v] of css.match(/:root\s*\{([\s\S]*?)\n\}/)[1].matchAll(/--([\w-]+):\s*(#[0-9A-Fa-f]{6})\b/g)) tok[k] = v.toUpperCase();

/* ---------- 1. product module: src/brand.gen.ts */
const PRODUCT_TOKENS = ['void', 'night', 'deep', 'line', 'line-2', 'fog', 'mute', 'snow', 'ink', 'signal', 'signal-2', 'redline', 'pad', 'margin', 'gap', 'marker'];

function productModule() {
  const missing = PRODUCT_TOKENS.filter((k) => !tok[k]);
  if (missing.length) throw new Error(`ps.css is missing tokens: ${missing.join(', ')}`);
  const key = (k) => (/^[a-z]\w*$/i.test(k) ? k : `'${k}'`);
  return [
    '// Generated by scripts/brand-export.mjs from site/assets/ps.css and site/assets/brand.js.',
    '// Do not edit by hand: change the brand files and run `npm run brand -- --product`.',
    '',
    'export const T = {',
    ...PRODUCT_TOKENS.map((k) => `  ${key(k)}: '${tok[k]}',`),
    '} as const;',
    '',
    '/** The mark: one solid path on a 7×7 grid (viewBox 0 0 7 7). Fill it with one color. */',
    'export const MARK = {',
    `  d: '${PS.MARK}',`,
    '  size: 7,',
    '} as const;',
    '',
    '/** PixelSpec icons used by the overlay: inner SVG markup on an 18-unit grid (viewBox 0 0 18 18), 1.5 stroke in currentColor. Source: scripts/icons.mjs. */',
    'export const ICONS = {',
    ...PRODUCT_ICONS.map((k) => {
      if (!ICONS[k]) throw new Error(`scripts/icons.mjs has no icon "${k}"`);
      if (ICONS[k].includes("'")) throw new Error(`icon "${k}" contains a single quote`);
      return `  ${key(k)}: '${ICONS[k]}',`;
    }),
    '} as const;',
    '',
    'export type IconName = keyof typeof ICONS;',
    '',
  ].join('\n');
}

{
  const file = at('src/brand.gen.ts');
  const next = productModule();
  if (process.argv.includes('--check')) {
    const cur = existsSync(file) ? readFileSync(file, 'utf8').replace(/\r\n/g, '\n') : '';
    if (cur !== next) { console.error('src/brand.gen.ts is out of date. Run `npm run brand -- --product`.'); process.exit(1); }
    console.log('product: src/brand.gen.ts is up to date');
    process.exit(0);
  }
  writeFileSync(file, next);
  console.log('product: wrote src/brand.gen.ts');
  if (process.argv.includes('--product')) process.exit(0);
}

/* ---------- 2. logo files */
const C = { void: tok.void, night: tok.night, snow: tok.snow, ink: tok.ink, signal: tok.signal, line: tok.line };

// Give an engine SVG a pixel size and drop page-only attributes.
function standalone(svg, height) {
  const [, , w, h] = svg.match(/viewBox="([-\d.\s]+)"/)[1].split(/\s+/).map(Number);
  return svg.replace(/ class="[^"]*"/, '').replace('<svg ', `<svg width="${Math.round((w / h) * height)}" height="${height}" `) + '\n';
}
const onDark = { mark: C.signal, word: C.snow, title: 'PixelSpec' };
const onLight = { mark: C.signal, word: C.ink, title: 'PixelSpec' };

// App icon and favicon: the white mark centred on a rounded Signal tile.
function tile(size, scale, r) {
  const o = (24 - 24 * scale) / 2;
  const k = (24 * scale) / 7;
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${size}" height="${size}" viewBox="0 0 24 24"><title>PixelSpec</title>` +
    `<rect width="24" height="24" rx="${r}" fill="${C.signal}"/>` +
    `<g transform="translate(${o} ${o}) scale(${k})">${PS.mark({ mark: '#FFFFFF' }).replace(/^<svg[^>]*>|<\/svg>$/g, '')}</g></svg>\n`;
}

const logos = {
  'mark-dark.svg': standalone(PS.mark(onDark), 96),
  'mark-light.svg': standalone(PS.mark(onLight), 96),
  'wordmark-dark.svg': standalone(PS.wordmark(onDark), 64),
  'wordmark-light.svg': standalone(PS.wordmark(onLight), 64),
  'lockup-dark.svg': standalone(PS.lockup(onDark), 64),
  'lockup-light.svg': standalone(PS.lockup(onLight), 64),
  'favicon.svg': tile(32, 0.66, 5.5),
  'app-icon.svg': tile(512, 0.56, 5.4),
};
mkdirSync(at('site/assets/logo'), { recursive: true });
for (const [name, body] of Object.entries(logos)) writeFileSync(at('site/assets/logo', name), body);
console.log(`logo: wrote ${Object.keys(logos).length} SVGs to site/assets/logo/`);

/* ---------- 3. icon sprite from scripts/icons.mjs */
{
  const symbols = Object.entries(ICONS).map(([id, body]) => `<symbol id="${id}" viewBox="0 0 18 18" fill="none">${body}</symbol>`);
  writeFileSync(at('site/assets/icons.svg'),
    `<svg xmlns="http://www.w3.org/2000/svg"><!-- PixelSpec icons, outline set on an 18 grid. Source: scripts/icons.mjs. Generated by scripts/brand-export.mjs. -->\n${symbols.join('\n')}\n</svg>\n`);
  console.log(`icons: wrote ${symbols.length} symbols to site/assets/icons.svg`);
}

if (process.argv.includes('--svg')) process.exit(0);

/* ---------- 4. PNGs via headless Chrome */
const chrome = [
  process.env.CHROME,
  'C:/Program Files/Google/Chrome/Application/chrome.exe',
  'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',
  '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',
  '/usr/bin/google-chrome',
  '/usr/bin/chromium',
].find((p) => p && existsSync(p));
if (!chrome) { console.error('No Chrome found. Set CHROME=/path/to/chrome.'); process.exit(1); }

const shots = [
  ['site/brand/posters/og.html', 'site/assets/og.png', 1200, 630],
  ['site/brand/posters/social-github.html', 'site/assets/social-github.png', 1280, 640],
  ['site/assets/logo/app-icon.svg', 'site/assets/logo/app-icon-180.png', 180, 180],
].filter(([page]) => existsSync(at(page)));
for (const [page, out, w, h] of shots) {
  let src = at(page);
  if (page.endsWith('.svg')) {
    // Resize a copy so the SVG fills the window exactly.
    src = join(tmpdir(), `pixelspec-${w}x${h}.svg`);
    writeFileSync(src, readFileSync(at(page), 'utf8').replace(/width="\d+" height="\d+"/, `width="${w}" height="${h}"`));
  }
  const url = pathToFileURL(src).href + (page.endsWith('.html') ? '?export' : '');
  const r = spawnSync(chrome, [
    '--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
    '--virtual-time-budget=6000', `--window-size=${w},${h}`, `--screenshot=${at(out)}`, url,
  ], { stdio: 'ignore' });
  console.log(`${r.status === 0 && existsSync(at(out)) ? 'png ' : 'FAIL'}: ${out} (${w}x${h})`);
}
